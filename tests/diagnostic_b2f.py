"""Local lab server with fixed, payload-free receive error categories."""
import sys
import re

from federated_cms import b2f
from federated_cms.b2_message import B2MessageError

read_message = b2f.Session.read_message
validate_message = b2f.validate_message


def diagnostic_validate(raw):
    try:
        return validate_message(raw)
    except B2MessageError as exc:
        if str(exc) == 'unexpected B2 trailing data' and b'\r\n\r\n' in raw:
            header, content = raw.split(b'\r\n\r\n', 1)
            sizes = []
            for line in header.split(b'\r\n'):
                name, _, value = line.partition(b':')
                if name.lower() in (b'body', b'file'):
                    token = value.strip().split(b' ', 1)[0]
                    if re.fullmatch(rb'[0-9]{1,6}', token):
                        sizes.append(int(token))
            pos = sum(sizes) + max(0, len(sizes) - 1) * 2
            trailing = content[pos:]
            print(f'Section diagnostic: sections={len(sizes)} trailing_bytes={len(trailing)} '
                  f'only_crlf={all(byte in (10, 13) for byte in trailing)} '
                  f'starts_crlf={trailing.startswith(bytes((13, 10)))} '
                  f'ends_crlf={trailing.endswith(bytes((13, 10)))} '
                  f'starts_nul={trailing.startswith(bytes((0,)))} '
                  f'ends_nul={trailing.endswith(bytes((0,)))} '
                  f'last_section_zero={bool(sizes and sizes[-1] == 0)}',
                  file=sys.stderr, flush=True)
        raise


b2f.validate_message = diagnostic_validate


def diagnostic_read_message(self, *args):
    try:
        return read_message(self, *args)
    except b2f.ProtocolError as exc:
        # These are fixed strings generated by the laboratory's parser, not
        # message fields or data. Never print arbitrary exception text.
        allowed = {'missing message header', 'unsupported message offset',
                   'message checksum error', 'invalid message block',
                   'compressed message too large', 'message length mismatch',
                   'message MID mismatch', 'invalid B2 message'}
        category = str(exc) if str(exc) in allowed else 'other protocol error'
        cause = exc.__cause__
        if isinstance(cause, B2MessageError):
            allowed_b2 = {'invalid B2 message', 'invalid B2 header', 'invalid B2 MID',
                          'invalid B2 body length', 'invalid B2 file header',
                          'truncated B2 section', 'missing B2 section separator',
                          'unexpected B2 trailing data'}
            if str(cause) in allowed_b2:
                category += ': ' + str(cause)
        print('Receive failure category: ' + category, file=sys.stderr, flush=True)
        raise
    except b2f.lzhuf.LzhufError:
        print('Receive failure category: compressed data', file=sys.stderr, flush=True)
        raise


b2f.Session.read_message = diagnostic_read_message

if __name__ == '__main__':
    b2f.main()
